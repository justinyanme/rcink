"""Bake VT323.ttf into Adafruit/M5GFX-compatible GFXfont C headers.

Mirrors the algorithm of Adafruit-GFX-Library's `fontconvert.c`:

  - FT_Set_Char_Size(face, ptSize*64, 0, DPI, 0)         (DPI = 141)
  - FT_Load_Char(c, FT_LOAD_TARGET_MONO) + FT_Render_Glyph
  - For each glyph: width, height, advance.x>>6, bitmap_left, 1-bitmap_top
  - Bitmap: continuous MSB-first bitstream per glyph, byte-padded between
    glyphs (NOT row-padded). yAdvance = metrics.height >> 6.

Outputs four headers under src/render/fonts/:
  vt323_9pt7b.h   vt323_12pt7b.h   vt323_18pt7b.h   vt323_24pt7b.h

Each declares a single `const lgfx::v1::GFXfont` named `VT323_<pt>pt7b` in the
`rcpaper::baked_fonts` namespace, plus the bitmap + glyph tables it references.

Run once after touching the source TTF or the sizes/range:

    uv run --with freetype-py --with httpx python tools/fonts/bake.py

Pure build-time tool; no firmware-side deps.
"""

from __future__ import annotations

import sys
from pathlib import Path

import freetype
import httpx

HERE = Path(__file__).parent
ROOT = HERE.resolve().parents[1]
OUT_DIR = ROOT / "src" / "render" / "fonts"
TTF_PATH = HERE / "VT323-Regular.ttf"
TTF_URL = "https://github.com/google/fonts/raw/main/ofl/vt323/VT323-Regular.ttf"

DPI = 141  # matches Adafruit fontconvert default
SIZES_PT = [13, 16, 18, 24]
FIRST = 0x20
LAST = 0x7E  # printable ASCII; CJK comes from the bundled efontCN_*


def ensure_ttf() -> Path:
    if TTF_PATH.exists():
        return TTF_PATH
    print(f"fetching {TTF_URL} -> {TTF_PATH}")
    r = httpx.get(TTF_URL, timeout=30, follow_redirects=True)
    r.raise_for_status()
    TTF_PATH.write_bytes(r.content)
    return TTF_PATH


def bake_size(face: freetype.Face, pt: int) -> tuple[list[int], list[dict], int]:
    """Return (bitmap_bytes, glyph_table_rows, y_advance) for one point size."""
    # FT_Set_Char_Size: size_x in 1/64 pt, size_y=0 (same), DPI in horiz/vert.
    face.set_char_size(pt * 64, 0, DPI, 0)

    bitmaps: list[int] = []
    glyphs: list[dict] = []

    for code in range(FIRST, LAST + 1):
        face.load_char(chr(code), freetype.FT_LOAD_TARGET_MONO)
        face.glyph.render(freetype.FT_RENDER_MODE_MONO)
        bmp = face.glyph.bitmap
        w, h = bmp.width, bmp.rows
        pitch = bmp.pitch
        buf = bmp.buffer

        bit_offset_start = len(bitmaps) * 8 + 0  # bit position from current byte boundary
        # Start each glyph on a byte boundary — that's what the runtime reader
        # expects when it does `if (!(bit++ & 7)) byte = bitmap[bo++]`.
        current_byte = 0
        bit_in_byte = 0  # 0..7, MSB-first

        for y in range(h):
            for x in range(w):
                src_byte = buf[y * pitch + (x // 8)]
                src_bit = 0x80 >> (x & 7)
                pixel = 1 if (src_byte & src_bit) else 0
                if pixel:
                    current_byte |= 0x80 >> bit_in_byte
                bit_in_byte += 1
                if bit_in_byte == 8:
                    bitmaps.append(current_byte)
                    current_byte = 0
                    bit_in_byte = 0
        # Flush trailing partial byte so the next glyph starts byte-aligned.
        if bit_in_byte > 0:
            bitmaps.append(current_byte)

        x_advance = face.glyph.advance.x >> 6
        x_offset = face.glyph.bitmap_left
        y_offset = 1 - face.glyph.bitmap_top

        glyphs.append(
            {
                "code": code,
                "char": chr(code) if 0x20 <= code < 0x7F else "?",
                # bitmap_offset for this glyph = (length BEFORE this glyph)
                "bitmap_offset": bit_offset_start // 8,
                "width": w,
                "height": h,
                "x_advance": x_advance,
                "x_offset": x_offset,
                "y_offset": y_offset,
            }
        )

    y_advance = face.size.height >> 6
    return bitmaps, glyphs, y_advance


def emit_header(pt: int, bitmaps: list[int], glyphs: list[dict], y_advance: int) -> str:
    name = f"VT323_{pt}pt7b"
    lines: list[str] = []
    lines.append("// AUTO-GENERATED by tools/fonts/bake.py. Do not edit by hand.")
    lines.append(f"// Source: VT323-Regular.ttf @ {pt}pt, {DPI}dpi, glyphs U+{FIRST:04X}–U+{LAST:04X}.")
    lines.append("#pragma once")
    lines.append("#ifdef ARDUINO")
    lines.append("#include <M5GFX.h>")
    lines.append("")
    lines.append("namespace rcpaper::baked_fonts {")
    lines.append("")
    lines.append(f"static const uint8_t {name}Bitmaps[] PROGMEM = {{")
    # 12 bytes per line for readability.
    for i in range(0, len(bitmaps), 12):
        chunk = ", ".join(f"0x{b:02X}" for b in bitmaps[i : i + 12])
        lines.append(f"  {chunk},")
    lines.append("};")
    lines.append("")
    lines.append(f"static const lgfx::v1::GFXglyph {name}Glyphs[] PROGMEM = {{")
    for g in glyphs:
        ch_repr = g["char"]
        if ch_repr in ("\\", "'", '"'):
            ch_repr = "\\" + ch_repr
        lines.append(
            f"  {{ {g['bitmap_offset']:5d}, {g['width']:3d}, {g['height']:3d},"
            f" {g['x_advance']:3d}, {g['x_offset']:4d}, {g['y_offset']:4d} }},"
            f"  // 0x{g['code']:02X} '{ch_repr}'"
        )
    lines.append("};")
    lines.append("")
    lines.append(f"const lgfx::v1::GFXfont {name} PROGMEM = {{")
    lines.append(f"  (uint8_t  *){name}Bitmaps,")
    lines.append(f"  (lgfx::v1::GFXglyph *){name}Glyphs,")
    lines.append(f"  0x{FIRST:02X}, 0x{LAST:02X}, {y_advance}")
    lines.append("};")
    lines.append("")
    lines.append("}  // namespace rcpaper::baked_fonts")
    lines.append("#endif  // ARDUINO")
    lines.append("")
    return "\n".join(lines)


def main() -> None:
    ttf = ensure_ttf()
    face = freetype.Face(str(ttf))
    OUT_DIR.mkdir(parents=True, exist_ok=True)

    for pt in SIZES_PT:
        bitmaps, glyphs, y_adv = bake_size(face, pt)
        header = emit_header(pt, bitmaps, glyphs, y_adv)
        out_path = OUT_DIR / f"vt323_{pt}pt7b.h"
        out_path.write_text(header)
        total_bytes = len(bitmaps) + len(glyphs) * 6
        print(
            f"  wrote {out_path.relative_to(ROOT)}: {len(glyphs)} glyphs,"
            f" {len(bitmaps)} bitmap bytes, ~{total_bytes} B on flash"
        )


if __name__ == "__main__":
    sys.exit(main())
