"""Bake the own waveforms (own_mono, own_color, own_grid) into src/own_waveforms.inc for the
on-device demo gallery. The Python tools stay the single source; `--check` fails when the
committed .inc is stale.

Usage: gen_demo_luts.py [--check]
"""

import sys
from pathlib import Path

TOOLS = Path(__file__).resolve().parent
sys.path.insert(0, str(TOOLS))
import own_color  # noqa: E402
import own_grid  # noqa: E402
import own_mono  # noqa: E402

OUT = TOOLS.parent / "src/own_waveforms.inc"


def render() -> str:
    base, modifier = own_grid.luts()
    tables = {
        "mono_clean": own_mono.lut(),
        "mono_fast": own_mono.fast_lut(),
        "color": own_color.lut(),
        "grid_base": base,
        "grid_modifier": modifier,
    }
    out = ["// Generated by tools/gen_demo_luts.py from the own_* tools. Do not edit.", ""]
    for name, table in tables.items():
        if len(table) != 799:
            raise ValueError(f"{name}: {len(table)} bytes, want 799")
        rows = [", ".join(f"0x{b:02x}" for b in table[i : i + 16]) for i in range(0, len(table), 16)]
        out += [f"static const uint8_t own_waveform_{name}[799] = {{", *(f"    {r}," for r in rows), "};", ""]
    return "\n".join(out)


def main() -> None:
    text = render()
    if "--check" in sys.argv[1:]:
        if not OUT.exists() or OUT.read_text() != text:
            sys.exit(f"{OUT} is stale: run tools/gen_demo_luts.py")
        return
    OUT.write_text(text)


if __name__ == "__main__":
    main()
