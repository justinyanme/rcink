#!/usr/bin/env python3
# /// script
# requires-python = ">=3.13"
# dependencies = ["pillow", "svg.path"]
# ///
"""Bake the usage-view provider logos into 1-bit bitmaps for the RLCD.

Sources are the single-colour 24x24 SVGs in tools/usage_logos/ (from the MIT
lobe-icons set; the marks themselves belong to their owners). Each path is
rasterized with even-odd fill at 16x supersampling and thresholded at 50 %
coverage, which matches the browser mock-up's canvas-then-threshold pipeline.

    uv run tools/bake_usage_logos.py            # rewrite src/render/usage_logos.h
    uv run tools/bake_usage_logos.py --check    # fail if the header is stale
    uv run tools/bake_usage_logos.py --preview  # print ASCII previews
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

from PIL import Image, ImageChops, ImageDraw
from svg.path import Close, Line, Move, parse_path

ROOT = Path(__file__).resolve().parent.parent
SOURCES = ROOT / "tools" / "usage_logos"
OUTPUT = ROOT / "src" / "render" / "usage_logos.h"
SUPERSAMPLE = 16
CURVE_STEPS = 24
# (logo id, pixel sizes). 28 px rows, 15 px headline pick, 12 px Antigravity tag.
LOGOS = [
    ("claude", (28, 15)),
    ("codex", (28, 15)),
    ("kimi", (28, 15)),
    ("gemini", (28, 15)),
    ("antigravity", (12,)),
]


def subpaths(d: str) -> list[list[tuple[float, float]]]:
    out: list[list[tuple[float, float]]] = []
    current: list[tuple[float, float]] = []
    for seg in parse_path(d):
        if isinstance(seg, Move):
            if len(current) > 2:
                out.append(current)
            current = [(seg.end.real, seg.end.imag)]
        elif isinstance(seg, (Line, Close)):
            current.append((seg.end.real, seg.end.imag))
        else:
            for k in range(1, CURVE_STEPS + 1):
                p = seg.point(k / CURVE_STEPS)
                current.append((p.real, p.imag))
    if len(current) > 2:
        out.append(current)
    return out


def rasterize(svg: str, size: int) -> list[list[bool]]:
    big = size * SUPERSAMPLE
    scale = big / 24.0
    union = Image.new("1", (big, big), 0)
    for d in re.findall(r'<path[^>]*?\sd="([^"]+)"', svg):
        evenodd = Image.new("1", (big, big), 0)
        for poly in subpaths(d):
            mask = Image.new("1", (big, big), 0)
            ImageDraw.Draw(mask).polygon([(x * scale, y * scale) for x, y in poly], fill=1)
            evenodd = ImageChops.logical_xor(evenodd, mask)
        union = ImageChops.logical_or(union, evenodd)
    coverage = union.convert("L").resize((size, size), Image.Resampling.BOX)
    return [[coverage.getpixel((x, y)) >= 128 for x in range(size)] for y in range(size)]


def pack(rows: list[list[bool]]) -> list[int]:
    out: list[int] = []
    for row in rows:
        for start in range(0, len(row), 8):
            byte = 0
            for bit, on in enumerate(row[start:start + 8]):
                if on:
                    byte |= 0x80 >> bit
            out.append(byte)
    return out


def symbol(logo: str, size: int) -> str:
    return f"k{logo.capitalize()}{size}"


def render_header() -> tuple[str, dict[str, list[list[bool]]]]:
    previews: dict[str, list[list[bool]]] = {}
    lines = [
        "// Generated by tools/bake_usage_logos.py from tools/usage_logos/*.svg.",
        "// Do not edit by hand. Provider marks belong to their respective owners.",
        "#pragma once",
        "",
        "#include <cstdint>",
        "",
        "namespace rcpaper {",
        "",
        "// Rows are MSB-first and padded to whole bytes (Adafruit GFX drawBitmap).",
        "struct MonoBitmap {",
        "  uint8_t w;",
        "  uint8_t h;",
        "  const uint8_t* bits;",
        "};",
        "",
        "namespace usage_logos {",
        "",
    ]
    for logo, sizes in LOGOS:
        svg = (SOURCES / f"{logo}.svg").read_text()
        for size in sizes:
            rows = rasterize(svg, size)
            previews[f"{logo}@{size}"] = rows
            data = pack(rows)
            name = symbol(logo, size)
            lines.append(f"constexpr uint8_t {name}Bits[] = {{")
            per_line = 12
            for i in range(0, len(data), per_line):
                chunk = ", ".join(f"0x{b:02X}" for b in data[i:i + per_line])
                lines.append(f"    {chunk},")
            lines.append("};")
            lines.append(f"constexpr MonoBitmap {name} = {{{size}, {size}, {name}Bits}};")
            lines.append("")
    lines += ["}  // namespace usage_logos", "}  // namespace rcpaper", ""]
    return "\n".join(lines), previews


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--preview", action="store_true")
    args = parser.parse_args()
    header, previews = render_header()
    if args.preview:
        for name, rows in previews.items():
            print(name)
            for row in rows:
                print("".join("#" if on else "." for on in row))
            print()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != header:
            print(f"{OUTPUT.relative_to(ROOT)} is stale; rerun tools/bake_usage_logos.py", file=sys.stderr)
            return 1
        return 0
    OUTPUT.write_text(header)
    print(f"wrote {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
