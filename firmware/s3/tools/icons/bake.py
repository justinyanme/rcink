#!/usr/bin/env python3
# /// script
# requires-python = ">=3.13"
# dependencies = ["pillow"]
# ///
"""Bake Lucide/Phosphor SVGs into a 1-bit C header for the firmware.

Reads SVGs from tools/icons/src/, rasterizes each to 16x16 and 24x24 PNG via
`rsvg-convert`, thresholds to 1-bit, and emits src/render/icons_data.h with
two arrays per glyph (`icon_<name>_16` and `icon_<name>_24`) plus an alias
mapping (icon name → bitmap). Run once after changing the SVG set:

    uv run tools/icons/bake.py

Pure build-time tool. No firmware-side dependencies.
"""

from __future__ import annotations

import shutil
import subprocess
import sys
from pathlib import Path

from PIL import Image

SRC = Path(__file__).parent / "src"
PNG = Path(__file__).parent / "png"
OUT = Path(__file__).resolve().parents[2] / "src" / "render" / "icons_data.h"

# Mapping from the DSL icon name (used in layout JSON) to the SVG file stem.
# Brand pseudo-names map to the closest geometric Lucide glyph; the `github`
# entry uses Phosphor's logo since Lucide removed brand marks.
NAME_TO_SVG = {
    "claude": "asterisk",
    "codex": "code",
    "calendar": "calendar",
    "todo": "square-check-big",
    "quote": "quote",
    "link": "link",
    "weather": "sun",
    "sun": "sun",
    "bell": "bell",
    "clock": "clock",
    "github": "github-logo",
    # Generic fallbacks
    "external": "external-link",
    # ---- new for top status bar ----
    "thermometer": "thermometer",
    "droplet": "droplet",
    "download": "download",
    "refresh": "refresh-cw",
}

SIZES = (16, 24)


def rasterize(svg: Path, size: int) -> Path:
    """SVG → PNG (size x size, black-on-white) via rsvg-convert."""
    out = PNG / f"{svg.stem}-{size}.png"
    cmd = [
        "rsvg-convert",
        "-w",
        str(size),
        "-h",
        str(size),
        "-b",
        "white",
        "-o",
        str(out),
        str(svg),
    ]
    subprocess.run(cmd, check=True)
    return out


def to_1bit_bytes(png_path: Path, size: int) -> tuple[bytes, str]:
    """Threshold to 1-bit, pack MSB-first into bytes_per_row * size bytes.

    Returns (bytes, ascii_art) — the ascii_art is purely for the header
    comment so the binary array stays self-documenting.
    """
    img = Image.open(png_path).convert("L").resize((size, size), Image.Resampling.LANCZOS)
    # Threshold at 128 — anything darker becomes "on" (a stroke pixel).
    bits = []
    art_rows = []
    for y in range(size):
        row = []
        art = []
        for x in range(size):
            v = img.getpixel((x, y))
            on = 1 if v < 128 else 0
            row.append(on)
            art.append("##" if on else "..")
        bits.append(row)
        art_rows.append("".join(art))

    # Pack MSB-first into bytes per row.
    bytes_per_row = (size + 7) // 8
    out = bytearray(bytes_per_row * size)
    for y in range(size):
        for x in range(size):
            if bits[y][x]:
                out[y * bytes_per_row + (x >> 3)] |= 0x80 >> (x & 7)
    return bytes(out), "\n".join("//   " + r for r in art_rows)


def emit_header(blobs: dict[tuple[str, int], tuple[bytes, str]]) -> str:
    out: list[str] = []
    out.append("// AUTO-GENERATED by tools/icons/bake.py — do not edit by hand.")
    out.append("//")
    out.append("// Source SVGs: Lucide (ISC) + Phosphor github-logo (MIT).")
    out.append("// See tools/icons/src/ for originals.")
    out.append("#pragma once")
    out.append("#include <cstdint>")
    out.append("")
    out.append("namespace rcpaper::icons {")
    out.append("")

    # Per-glyph byte arrays.
    unique_stems = sorted({stem for stem, _ in blobs})
    for stem in unique_stems:
        for size in SIZES:
            data, art = blobs[(stem, size)]
            sym = f"{stem.replace('-', '_')}_{size}"
            out.append(f"// {stem} @ {size}x{size}")
            out.append(art)
            out.append(f"constexpr uint8_t {sym}[] = {{")
            row = []
            bytes_per_row = (size + 7) // 8
            for i, b in enumerate(data):
                row.append(f"0x{b:02X}")
                if (i + 1) % bytes_per_row == 0:
                    out.append("  " + ", ".join(row) + ",")
                    row = []
            out.append("};")
            out.append("")

    # Lookup table: DSL name → bitmap pointer per size.
    out.append("struct Glyph { const uint8_t* px16; const uint8_t* px24; };")
    out.append("")
    out.append("// String-keyed lookup. NULL marks the end.")
    out.append("struct NamedGlyph { const char* name; Glyph glyph; };")
    out.append("constexpr NamedGlyph kGlyphs[] = {")
    for dsl_name, stem in sorted(NAME_TO_SVG.items()):
        sym16 = f"{stem.replace('-', '_')}_16"
        sym24 = f"{stem.replace('-', '_')}_24"
        out.append(f'  {{"{dsl_name}", {{ {sym16}, {sym24} }}}},')
    out.append("  {nullptr, {nullptr, nullptr}},")
    out.append("};")
    out.append("")
    out.append("}  // namespace rcpaper::icons")
    out.append("")
    return "\n".join(out)


def main() -> None:
    if not shutil.which("rsvg-convert"):
        sys.exit("rsvg-convert not on PATH — `brew install librsvg`.")
    PNG.mkdir(exist_ok=True)
    blobs: dict[tuple[str, int], tuple[bytes, str]] = {}
    stems = sorted({stem for stem in NAME_TO_SVG.values()})
    for stem in stems:
        svg = SRC / f"{stem}.svg"
        if not svg.exists():
            sys.exit(f"missing SVG: {svg}")
        for size in SIZES:
            png = rasterize(svg, size)
            blobs[(stem, size)] = to_1bit_bytes(png, size)
    OUT.write_text(emit_header(blobs))
    print(f"wrote {OUT}  ({len(stems)} glyphs × {len(SIZES)} sizes)")


if __name__ == "__main__":
    main()
